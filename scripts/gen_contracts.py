"""Export the Pydantic contracts to JSON Schema and TypeScript.

    python scripts/gen_contracts.py          # write packages/contracts/schema + ts/generated.ts
    python scripts/gen_contracts.py --check  # exit 1 if either file is out of date (used by tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from pydantic.json_schema import models_json_schema

from oar_contracts import CONTRACT_VERSION, EXPORTED_ENUMS, EXPORTED_MODELS

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "packages" / "contracts" / "schema" / "contracts.schema.json"
TS = ROOT / "packages" / "contracts" / "ts" / "generated.ts"


def schema() -> dict:
    _, top = models_json_schema([(m, "serialization") for m in EXPORTED_MODELS],
                                ref_template="#/$defs/{model}", title="OpenAMRobot AI Studio contracts")
    top["$id"] = f"https://github.com/openamrobot-ai-studio/contracts/{CONTRACT_VERSION}"
    top["x-contract-version"] = CONTRACT_VERSION
    return top


def ts_type(s: dict) -> str:
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "anyOf" in s:
        return " | ".join(dict.fromkeys(ts_type(x) for x in s["anyOf"]))
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    if "const" in s:
        return json.dumps(s["const"])
    t = s.get("type")
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        return f"Array<{ts_type(s.get('items', {}))}>"
    if t == "object":
        ap = s.get("additionalProperties")
        return f"Record<string, {ts_type(ap) if isinstance(ap, dict) and ap else 'unknown'}>"
    return "unknown"


def typescript(sch: dict) -> str:
    out = ["// GENERATED by scripts/gen_contracts.py from packages/contracts/oar_contracts/models.py. Do not edit.",
           f'export const CONTRACT_VERSION = "{CONTRACT_VERSION}";', ""]
    defs = sch["$defs"]
    for name in sorted(defs):
        d = defs[name]
        if "enum" in d:
            out.append(f"export type {name} = {' | '.join(json.dumps(v) for v in d['enum'])};")
            out.append(f"export const {name}Values = [{', '.join(json.dumps(v) for v in d['enum'])}] as const;\n")
            continue
        out.append(f"export interface {name} {{")
        req = set(d.get("required", []))
        for prop, ps in d.get("properties", {}).items():
            doc = ps.get("description")
            if doc:
                out.append(f"  /** {doc} */")
            out.append(f"  {prop}{'' if prop in req else '?'}: {ts_type(ps)};")
        out.append("}\n")
    return "\n".join(out)


def main() -> int:
    sch = schema()
    sch_txt = json.dumps(sch, indent=2, sort_keys=True) + "\n"
    ts_txt = typescript(sch)
    for e in EXPORTED_ENUMS:
        assert e.__name__ in sch["$defs"], f"enum {e.__name__} missing from schema"
    if "--check" in sys.argv:
        stale = [p for p, txt in ((SCHEMA, sch_txt), (TS, ts_txt))
                 if not p.exists() or p.read_text(encoding="utf-8") != txt]
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)} (run python scripts/gen_contracts.py)")
        return 1 if stale else 0
    SCHEMA.parent.mkdir(parents=True, exist_ok=True)
    SCHEMA.write_text(sch_txt, encoding="utf-8", newline="\n")
    TS.write_text(ts_txt, encoding="utf-8", newline="\n")
    print("wrote", SCHEMA.relative_to(ROOT), TS.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
